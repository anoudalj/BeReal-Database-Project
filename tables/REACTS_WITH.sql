CREATE TABLE `REACTS_WITH` (
    `UserID` INT NOT NULL,
    `PostID` INT NOT NULL,
    `RealMojiID` INT NOT NULL,

    PRIMARY KEY (`UserID`, `PostID`, `RealMojiID`) USING BTREE,

    INDEX `FK_REACTS_WITH_POST` (`PostID`) USING BTREE,
    INDEX `FK_REACTS_WITH_REALMOJIS` (`RealMojiID`) USING BTREE,

    CONSTRAINT `FK_REACTS_WITH_POST`
        FOREIGN KEY (`PostID`)
        REFERENCES `POST` (`PostID`)
        ON UPDATE NO ACTION ON DELETE CASCADE,

    CONSTRAINT `FK_REACTS_WITH_REALMOJIS`
        FOREIGN KEY (`RealMojiID`)
        REFERENCES `REALMOJIS` (`RealMojiID`)
        ON UPDATE NO ACTION ON DELETE NO ACTION,

    CONSTRAINT `FK_REACTS_WITH_USER`
        FOREIGN KEY (`UserID`)
        REFERENCES `USER` (`UserID`)
        ON UPDATE NO ACTION ON DELETE NO ACTION
)
COLLATE='utf8mb4_0900_ai_ci'
ENGINE=InnoDB;
